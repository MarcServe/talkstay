/**
 * Enhanced iframe compatibility detection with progressive timeouts
 */
export const checkIframeCompatibility = async (url: string, timeout: number = 8000): Promise<{
  compatible: boolean;
  reason?: string;
  suggestions: string[];
}> => {
  try {
    // Use a more sophisticated approach with timeout control
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), timeout);
    
    const response = await fetch(url, { 
      method: 'HEAD',
      mode: 'no-cors',
      signal: controller.signal
    });
    
    clearTimeout(timeoutId);
    
    // Optimistic approach - assume compatible unless we detect specific issues
    return {
      compatible: true,
      suggestions: [
        'Website appears to be accessible',
        'iframe embedding should work',
        'Monitor for any security policy blocks'
      ]
    };
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : 'Unknown error';
    
    if (errorMessage.includes('abort')) {
      return {
        compatible: false,
        reason: `Website took longer than ${timeout/1000}s to respond`,
        suggestions: [
          'Try increasing the timeout duration',
          'Check if website is experiencing high traffic',
          'Use Widget Only mode as alternative'
        ]
      };
    }
    
    return {
      compatible: false,
      reason: errorMessage,
      suggestions: [
        'Check if the website URL is correct',
        'Verify network connectivity',
        'Try Widget Only preview mode'
      ]
    };
  }
};

